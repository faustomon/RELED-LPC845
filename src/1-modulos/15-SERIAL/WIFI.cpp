char aux1[13];
uint8_t inx;

void checkPuerto() {
	if ( (inx = uart0.Message(aux1,12)) )
	{
		aux1[inx+1] = '\0';
		uint8_t *pTxt= (uint8_t*)&aux1[0];
		ParseoData(pTxt);
		memset(aux1, 0, sizeof(aux1));
	}
}

void ParseoData(uint8_t *pTxt)
{

    // CLOCK: Hhora (ej: H1243)
    if (pTxt[0] == 'H' && pTxt)
    {
        m_Clock_Hora = (pTxt[1] - '0') * 10 + (pTxt[2] - '0');  	// Para las horas
        m_Clock_Minutos = (pTxt[3] - '0') * 10 + (pTxt[4] - '0');  // Para los minutos
        rtc->SetupHour(m_Clock_Hora, m_Clock_Minutos, 0); // le pongo 10 por ponerle algo, no nos interesa que se configuren los segs
    }
    // ALARMA: A estado_hora (ej: A1011250)
    else if (pTxt[0] == 'A')
    {
        m_Alarma_Activada = (pTxt[1] == '1');
        m_Amanecer_Activado = (pTxt[2] == '1');
        m_Buzzer_Activado = (pTxt[3] == '1');

        m_Alarma_Hora = (pTxt[4] - '0') * 10 + (pTxt[5] - '0');  	// Para las horas
        m_Alarma_Minutos = (pTxt[6] - '0') * 10 + (pTxt[7] - '0');   // Para los minutos
    }
    // TIMER: T hora hora hora (ej: R050025000500)
    else if (pTxt[0] == 'R')
    {

        m_Tempo_minutos = (pTxt[1] - '0') * 10 + (pTxt[2] - '0');  	// Para las horas
        m_Tempo_segundos = (pTxt[3] - '0') * 10 + (pTxt[4] - '0');   // Para los minutos
        m_Work_minutos = (pTxt[5] - '0') * 10 + (pTxt[6] - '0');  	// Para las horas
        m_Work_segundos = (pTxt[7] - '0') * 10 + (pTxt[8] - '0');   // Para los minutos
        m_Break_minutos = (pTxt[9] - '0') * 10 + (pTxt[10] - '0');  	// Para las horas
        m_Break_segundos = (pTxt[11] - '0') * 10 + (pTxt[12] - '0');   // Para los minutos
    }
    // CLIMA: Ttemp (ej: T253)
    else if (pTxt[0] == 'T')
    {

        m_Temperatura = (pTxt[1] - '0') * 10 + (pTxt[2] - '0') ;
        m_Temperatura_decimal = (pTxt[3] - '0') * 10 + (pTxt[4] - '0');

    }
}
